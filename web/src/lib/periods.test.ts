import { describe, expect, it } from 'vitest';
import { periodKind, readPeriod, writePeriod } from './periods.ts';

describe('periods', () => {
	it('are what their ends make them', () => {
		expect(periodKind('2026-09-15', '2026-09-15')).toBe('day');
		expect(periodKind('2026-09-14', '2026-09-20')).toBe('week');
		expect(periodKind('2026-09-15', '2026-09-21')).toBe('span'); // Tuesday to Monday
		expect(periodKind('2028-02-01', '2028-02-29')).toBe('month');
		expect(periodKind('2026-07-01', '2026-09-30')).toBe('quarter');
		expect(periodKind('2026-02-01', '2026-04-30')).toBe('span');
		expect(periodKind('2025-01-01', '2025-12-31')).toBe('year');
	});

	it('are written in ISO 8601, a quarter as 2026-Q3', () => {
		expect(writePeriod('2026-09-01', '2026-09-30')).toBe('2026-09');
		expect(writePeriod('2026-09-14', '2026-09-20')).toBe('2026-W38');
		expect(writePeriod('2026-12-28', '2027-01-03')).toBe('2026-W53');
		expect(writePeriod('2025-12-29', '2026-01-04')).toBe('2026-W01');
		expect(writePeriod('2026-07-01', '2026-09-30')).toBe('2026-Q3');
		expect(writePeriod('2025-01-01', '2025-12-31')).toBe('2025');
		expect(writePeriod('2026-09-15', '2026-09-15')).toBe('2026-09-15');
		expect(writePeriod('2026-09-01', '2026-09-14')).toBe('2026-09-01/2026-09-14');
		// Not (yet) a period.
		expect(writePeriod('2026-09-01', '')).toBe('');
		expect(writePeriod('2026-09-30', '2026-09-01')).toBe('');
	});

	it.each([
		['2026', '2026-01-01', '2026-12-31'],
		['2026-Q2', '2026-04-01', '2026-06-30'],
		['2026q4', '2026-10-01', '2026-12-31'],
		['2026-03', '2026-03-01', '2026-03-31'],
		['2028-02', '2028-02-01', '2028-02-29'],
		['2026-W17', '2026-04-20', '2026-04-26'],
		['2026-w1', '2025-12-29', '2026-01-04'],
		['2026-03-31', '2026-03-31', '2026-03-31'],
		['2026-03-01/2026-03-14', '2026-03-01', '2026-03-14'],
		['KW 17/2026', '2026-04-20', '2026-04-26'],
		['kw17 2026', '2026-04-20', '2026-04-26'],
		['Week 17, 2026', '2026-04-20', '2026-04-26'],
		['Q2 2026', '2026-04-01', '2026-06-30'],
		['Q2/2026', '2026-04-01', '2026-06-30'],
		['03/2026', '2026-03-01', '2026-03-31'],
		['3.2026', '2026-03-01', '2026-03-31'],
		['März 2026', '2026-03-01', '2026-03-31'],
		['Maerz 2026', '2026-03-01', '2026-03-31'],
		['Sept. 2026', '2026-09-01', '2026-09-30'],
		['May 2026', '2026-05-01', '2026-05-31'],
		['31.03.2026', '2026-03-31', '2026-03-31'],
		['1.3.2026', '2026-03-01', '2026-03-01'],
		['01.03.2026–14.03.2026', '2026-03-01', '2026-03-14'],
		['01.03.2026 - 14.03.2026', '2026-03-01', '2026-03-14'],
		['1.3.2026 bis 14.3.2026', '2026-03-01', '2026-03-14'],
		['2026-03/2026-05', '2026-03-01', '2026-05-31'],
		['KW 17/2026 – KW 18/2026', '2026-04-20', '2026-05-03'],
		['  2026-Q2  ', '2026-04-01', '2026-06-30']
	])('reads %s', (text, start, end) => {
		expect(readPeriod(text)).toEqual({ start, end });
	});

	it.each([
		'',
		'2026-13',
		'2026-Q5',
		'2027-W53', // 2027 has 52 weeks (2026 has 53)
		'31.02.2026',
		'Ma 2026',
		'Montag 2026',
		'2026-03-14/2026-03-01',
		'irgendwann'
	])('does not read %j', (text) => {
		expect(readPeriod(text)).toBeNull();
	});

	it('reads what it writes', () => {
		for (const [start, end] of [
			['2026-09-01', '2026-09-30'],
			['2026-12-28', '2027-01-03'],
			['2026-07-01', '2026-09-30'],
			['2025-01-01', '2025-12-31'],
			['2026-09-15', '2026-09-15'],
			['2026-09-01', '2026-09-14']
		]) {
			expect(readPeriod(writePeriod(start, end))).toEqual({ start, end });
		}
	});
});
